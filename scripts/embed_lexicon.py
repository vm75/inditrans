#!/usr/bin/env python3
"""Embed a compiled lexicon; consumes only the pack and its technical build report."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import struct
import zlib


def generate(raw, script, source):
    if not re.fullmatch('[a-z][a-z0-9_]*', script):
        raise ValueError('script is not a valid generated namespace identifier')
    if len(raw) < 16 or raw[:4] not in (b'IUL1', b'IUL2'):
        raise ValueError('invalid lexicon envelope')
    if struct.unpack_from('<I', raw, 4)[0] != zlib.crc32(raw[8:]):
        raise ValueError('lexicon CRC mismatch')
    chunks = ['    "' + ''.join(f'\\x{byte:02x}' for byte in raw[i:i + 32]) + '"'
              for i in range(0, len(raw), 32)]
    return (f'// Generated by scripts/embed_lexicon.py from {source}.\n'
            '#pragma once\n\n'
            f'namespace inditrans::embedded_{script} {{\n'
            'inline constexpr char pack[] =\n' + '\n'.join(chunks) + ';\n'
            'inline constexpr unsigned long pack_size = sizeof(pack) - 1;\n'
            f'static_assert(pack_size == {len(raw)});\n'
            f'}} // namespace inditrans::embedded_{script}\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--script', required=True)
    parser.add_argument('--source', type=Path, required=True)
    parser.add_argument('--report', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    raw = args.source.read_bytes()
    report = json.loads(args.report.read_text())
    if report.get('script') != args.script or report.get('pack_sha256') != hashlib.sha256(raw).hexdigest():
        parser.error('pack does not match the script and hash in its build report')
    try:
        result = generate(raw, args.script, args.source.as_posix())
    except ValueError as error:
        parser.error(str(error))
    if args.check:
        if not args.output.exists() or args.output.read_text() != result:
            parser.error('embedded header is stale')
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(result, encoding='utf-8')
    print(f'{args.script}: embedded {len(raw)} lexicon bytes; check={args.check}')


if __name__ == '__main__':
    main()
